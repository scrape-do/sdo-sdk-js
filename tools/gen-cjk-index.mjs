// Generates src/cjk-index.ts, the compact WHATWG index tables behind the
// euc-kr, big5 and Shift_JIS decoders in src/cjk.ts. The module is imported
// lazily, only when a response needs one of those encodings.
//
// The index files come from the WHATWG Encoding Standard; this script never
// downloads anything. To regenerate:
//
//   mkdir -p /tmp/whatwg-index && cd /tmp/whatwg-index
//   for n in euc-kr big5 jis0208; do curl -fsSLO "https://encoding.spec.whatwg.org/index-$n.txt"; done
//   cd -
//   node tools/gen-cjk-index.mjs /tmp/whatwg-index           # rewrites src/cjk-index.ts
//   node tools/gen-cjk-index.mjs /tmp/whatwg-index --check   # exit 1 when it is stale
//
// Then run the test suite (test/cjk.test.ts spot-checks the tables).
//
// Table format: for each mapped pointer in ascending order, two unsigned
// varints: the gap since the previous mapped pointer minus one (the first
// "previous" is -1), then the zigzag-encoded difference between this code
// point and the previous one plus one (the first "previous" is 0). A varint is
// little-endian base-32 digits, each written as one character of
// A-Z a-z 0-9 + / with the value 32 added while more digits follow.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const TABLES = [
  { name: "EUC_KR", file: "index-euc-kr.txt" },
  { name: "BIG5", file: "index-big5.txt" },
  { name: "JIS0208", file: "index-jis0208.txt" },
];

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src", "cjk-index.ts");

const [dir, flag] = process.argv.slice(2);
if (!dir || (flag !== undefined && flag !== "--check")) {
  process.stderr.write("usage: node tools/gen-cjk-index.mjs <dir with index-*.txt> [--check]\n");
  process.exit(2);
}

function varint(n) {
  let out = "";
  do {
    let digit = n % 32;
    n = Math.floor(n / 32);
    if (n > 0) digit += 32;
    out += ALPHABET[digit];
  } while (n > 0);
  return out;
}

const zigzag = (n) => (n >= 0 ? n * 2 : -n * 2 - 1);

function encode(file) {
  const text = readFileSync(join(dir, file), "utf8");
  const identifier = /^# Identifier: ([0-9a-f]+)$/m.exec(text)?.[1];
  const date = /^# Date: (\S+)$/m.exec(text)?.[1];
  if (!identifier || !date) throw new Error(`${file}: no Identifier/Date header; is it a WHATWG index file?`);
  const entries = [];
  for (const line of text.split("\n")) {
    const m = /^\s*(\d+)\t0x([0-9A-F]+)\t/.exec(line);
    if (m) entries.push([Number(m[1]), parseInt(m[2], 16)]);
  }
  entries.sort((a, b) => a[0] - b[0]);
  let prevPointer = -1;
  let prevCodePoint = 0;
  let data = "";
  for (const [pointer, codePoint] of entries) {
    if (pointer === prevPointer) throw new Error(`${file}: pointer ${pointer} listed twice`);
    data += varint(pointer - prevPointer - 1) + varint(zigzag(codePoint - prevCodePoint - 1));
    prevPointer = pointer;
    prevCodePoint = codePoint;
  }
  return { identifier, date, size: prevPointer + 1, count: entries.length, data };
}

const lines = [
  "// SPDX-License-Identifier: Apache-2.0 AND BSD-3-Clause",
  "// GENERATED by tools/gen-cjk-index.mjs; do not edit. See that script for the",
  "// format and for how to regenerate it.",
  "//",
  "// Derived from the index files of the WHATWG Encoding Standard",
  "// (https://encoding.spec.whatwg.org/), Copyright © WHATWG (Apple, Google,",
  "// Mozilla, Microsoft), which are licensed under the BSD 3-Clause License where",
  "// they are incorporated into source code. See NOTICE.",
  "//",
];
const body = [];
for (const { name, file } of TABLES) {
  const t = encode(file);
  lines.push(`//   ${file}: ${t.count} mappings, Identifier ${t.identifier}, Date ${t.date}`);
  body.push("", `export const ${name}_SIZE = ${t.size};`, `export const ${name} =`, `  "${t.data}";`);
}
const out = [...lines, ...body].join("\n") + "\n";

if (flag === "--check") {
  const current = readFileSync(OUT, "utf8");
  if (current !== out) {
    process.stderr.write("gen-cjk-index: src/cjk-index.ts is stale; rerun without --check.\n");
    process.exit(1);
  }
  process.stdout.write("gen-cjk-index: src/cjk-index.ts is up to date.\n");
} else {
  writeFileSync(OUT, out);
  process.stdout.write(`gen-cjk-index: wrote ${OUT} (${out.length} bytes)\n`);
}
