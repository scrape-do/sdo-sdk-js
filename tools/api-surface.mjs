// Deterministic public-API surface extractor.
//
//   node tools/api-surface.mjs            # writes api-surface.txt
//
// Emits declarations in memory with the installed TypeScript compiler, keeps
// the symbols re-exported from the package entry (src/index.ts) and writes one
// line per public symbol or member, sorted, to `api-surface.txt`. CI regenerates
// it and fails when `git diff api-surface.txt` is non-empty.
//
// Line grammar: `<kind> <owner> [<rest>]`, single spaces. The owner of a member
// is the thing it belongs to, so a release diff can tell an added optional
// member (compatible) from an added required one (breaking):
//
//   class <Name> [extends <Base>]            interface <Name> [extends <Base>]
//   ctor <Name>.constructor                  type <Name> = <type>
//   method <Name>.<m> -> <return type>       func <name> -> <return type>
//   param <Owner> #<i> <name>: <type> [required]   (a positional parameter)
//   param <Owner> #<i> <name>?: <type>             (optional; Owner = Name.m / fn)
//   prop <Name> <name>: <type> [readonly]    (class property or getter)
//   prop <Iface> <name>?: <type>             (optional interface member)
//   prop <Iface> <name>: <type> [required]   (required member of an input type:
//                                             an interface callers construct)
//   const <NAME>: <type>                     (never the value)
//
// Private members (TypeScript `private` and `#fields`) are not API. No version
// strings and no doc comments appear, so a release or a reworded comment does
// not change the golden.

import { writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(repoRoot, "api-surface.txt");
const HEADER = [
  "# sdo-sdk-js public API surface. Generated by tools/api-surface.mjs; do not edit.",
  "# Regenerate with `npm run api:surface` and commit it with any API change.",
];

function emitDeclarations() {
  const configFile = join(repoRoot, "tsconfig.json");
  const parsed = ts.getParsedCommandLineOfConfigFile(configFile, {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => {
      throw new Error(ts.flattenDiagnosticMessageText(d.messageText, "\n"));
    },
  });
  const options = { ...parsed.options, declaration: true, emitDeclarationOnly: true, noEmit: false, outDir: "/api" };
  const program = ts.createProgram([join(repoRoot, "src", "index.ts")], options);
  const files = new Map();
  const result = program.emit(undefined, (name, text) => files.set(basename(name), text), undefined, true);
  const errors = ts.getPreEmitDiagnostics(program).concat(result.diagnostics);
  if (errors.length > 0) {
    throw new Error(ts.formatDiagnostics(errors, { getCanonicalFileName: (f) => f, getCurrentDirectory: () => repoRoot, getNewLine: () => "\n" }));
  }
  return files;
}

const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });
const text = (node, sf) => printer.printNode(ts.EmitHint.Unspecified, node, sf).replace(/\s+/g, " ").trim();
const typeText = (node, sf) => (node ? text(node, sf) : "any");
const isPrivate = (m) =>
  (m.name && ts.isPrivateIdentifier(m.name)) ||
  (ts.getCombinedModifierFlags(m) & ts.ModifierFlags.Private) !== 0;
const isReadonly = (m) => (ts.getCombinedModifierFlags(m) & ts.ModifierFlags.Readonly) !== 0;
const isStatic = (m) => (ts.getCombinedModifierFlags(m) & ts.ModifierFlags.Static) !== 0;

/** Public names re-exported from index.d.ts -> { file, local } of their declaration. */
function readExports(files) {
  const sf = ts.createSourceFile("index.d.ts", files.get("index.d.ts"), ts.ScriptTarget.Latest, true);
  const out = new Map();
  for (const stmt of sf.statements) {
    if (!ts.isExportDeclaration(stmt) || !stmt.moduleSpecifier || !stmt.exportClause) continue;
    const file = stmt.moduleSpecifier.text.replace(/^\.\//, "").replace(/\.js$/, ".d.ts");
    for (const el of stmt.exportClause.elements) {
      out.set(el.name.text, { file, local: (el.propertyName ?? el.name).text });
    }
  }
  return out;
}

/** Top-level declarations of one emitted file, by name (overloads grouped). */
function declarations(files, file) {
  const sf = ts.createSourceFile(file, files.get(file), ts.ScriptTarget.Latest, true);
  const decls = new Map();
  const add = (name, node) => decls.set(name, [...(decls.get(name) ?? []), node]);
  for (const stmt of sf.statements) {
    if (ts.isVariableStatement(stmt)) for (const d of stmt.declarationList.declarations) add(d.name.text, d);
    else if (stmt.name && ts.isIdentifier(stmt.name)) add(stmt.name.text, stmt);
  }
  return { sf, decls };
}

/** Names of the types a node refers to (to find interfaces used as inputs). */
function referencedTypes(node) {
  const names = new Set();
  const visit = (n) => {
    if (ts.isTypeReferenceNode(n) && ts.isIdentifier(n.typeName)) names.add(n.typeName.text);
    ts.forEachChild(n, visit);
  };
  if (node) visit(node);
  return names;
}

// Type parameters stay out of the owner token: ` [generic <T = unknown>]`.
const generics = (fn, sf) =>
  fn.typeParameters?.length ? ` [generic <${fn.typeParameters.map((t) => text(t, sf)).join(", ")}>]` : "";

function heritage(node, sf) {
  const clauses = node.heritageClauses ?? [];
  return clauses.map((c) => ` ${c.token === ts.SyntaxKind.ExtendsKeyword ? "extends" : "implements"} ${c.types.map((t) => text(t, sf)).join(", ")}`).join("");
}

function main() {
  const files = emitDeclarations();
  const exported = readExports(files);
  const lines = new Set();
  const inputTypes = new Set();
  const interfaces = [];
  const parsedFiles = new Map();

  const paramLines = (owner, fn, sf) => {
    fn.parameters.forEach((p, i) => {
      const name = (p.dotDotDotToken ? "..." : "") + text(p.name, sf);
      const optional = Boolean(p.questionToken || p.initializer || p.dotDotDotToken);
      for (const t of referencedTypes(p.type)) inputTypes.add(t);
      lines.add(`param ${owner} #${i} ${name}${optional ? "?" : ""}: ${typeText(p.type, sf)}${optional ? "" : " [required]"}`);
    });
  };

  for (const [name, { file, local }] of exported) {
    if (!parsedFiles.has(file)) parsedFiles.set(file, declarations(files, file));
    const { sf, decls } = parsedFiles.get(file);
    const nodes = decls.get(local);
    if (!nodes) throw new Error(`public symbol ${name} has no declaration in ${file}`);
    for (const node of nodes) {
      if (ts.isClassDeclaration(node)) {
        lines.add(`class ${name}${heritage(node, sf)}`);
        for (const m of node.members) {
          if (isPrivate(m)) continue;
          const flags = isStatic(m) ? " [static]" : "";
          if (ts.isConstructorDeclaration(m)) {
            lines.add(`ctor ${name}.constructor`);
            paramLines(`${name}.constructor`, m, sf);
          } else if (ts.isPropertyDeclaration(m)) {
            const opt = m.questionToken ? "?" : "";
            lines.add(`prop ${name} ${text(m.name, sf)}${opt}: ${typeText(m.type, sf)}${isReadonly(m) ? " [readonly]" : ""}${flags}`);
          } else if (ts.isGetAccessorDeclaration(m)) {
            const settable = node.members.some((o) => ts.isSetAccessorDeclaration(o) && text(o.name, sf) === text(m.name, sf));
            lines.add(`prop ${name} ${text(m.name, sf)}: ${typeText(m.type, sf)}${settable ? "" : " [readonly]"}${flags}`);
          } else if (ts.isMethodDeclaration(m)) {
            const owner = `${name}.${text(m.name, sf)}`;
            lines.add(`method ${owner} -> ${typeText(m.type, sf)}${generics(m, sf)}${flags}`);
            paramLines(owner, m, sf);
          }
        }
      } else if (ts.isInterfaceDeclaration(node)) {
        lines.add(`interface ${name}${heritage(node, sf)}`);
        interfaces.push({ name, node, sf });
      } else if (ts.isTypeAliasDeclaration(node)) {
        lines.add(`type ${name} = ${typeText(node.type, sf)}`);
        for (const t of referencedTypes(node.type)) inputTypes.add(t);
      } else if (ts.isFunctionDeclaration(node)) {
        lines.add(`func ${name} -> ${typeText(node.type, sf)}${generics(node, sf)}`);
        paramLines(name, node, sf);
      } else if (ts.isVariableDeclaration(node)) {
        // `export declare const VERSION = "0.1.0"` carries its value as the type;
        // only the kind of value is API.
        const init = node.initializer;
        const kind = !init ? "unknown" : ts.isStringLiteral(init) ? "string" : ts.isNumericLiteral(init) ? "number" : "unknown";
        lines.add(`const ${name}: ${node.type ? typeText(node.type, sf) : kind}`);
      }
    }
  }

  // An interface is an input type when a parameter mentions it, directly or
  // through another input interface or its base.
  let grew = true;
  while (grew) {
    grew = false;
    for (const { name, node, sf } of interfaces) {
      if (!inputTypes.has(name)) continue;
      const refs = [...(node.heritageClauses ?? []).flatMap((c) => c.types.map((t) => text(t.expression, sf)))];
      for (const m of node.members) for (const t of referencedTypes(m.type)) refs.push(t);
      for (const r of refs) if (!inputTypes.has(r)) (inputTypes.add(r), (grew = true));
    }
  }

  for (const { name, node, sf } of interfaces) {
    const input = inputTypes.has(name);
    for (const m of node.members) {
      if (ts.isPropertySignature(m)) {
        const optional = Boolean(m.questionToken);
        const required = input && !optional ? " [required]" : "";
        lines.add(`prop ${name} ${text(m.name, sf)}${optional ? "?" : ""}: ${typeText(m.type, sf)}${required}`);
      } else if (ts.isMethodSignature(m)) {
        const owner = `${name}.${text(m.name, sf)}`;
        lines.add(`method ${owner} -> ${typeText(m.type, sf)}${generics(m, sf)}${input ? " [required]" : ""}`);
        paramLines(owner, m, sf);
      }
    }
  }

  const sorted = [...lines].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  writeFileSync(OUT, [...HEADER, ...sorted].join("\n") + "\n");
  process.stdout.write(`api-surface: ${sorted.length} line(s) -> api-surface.txt\n`);
}

main();
